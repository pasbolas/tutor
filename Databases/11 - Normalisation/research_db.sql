-- Drop in dependency order
DROP TABLE IF EXISTS research_grant, research_publication, grant_funding, publication, research, scientist, department, university;

-- Base tables
CREATE TABLE university (
  uni_id   INT PRIMARY KEY,
  uniname  VARCHAR(100),
  country  VARCHAR(60)
);

CREATE TABLE department (
  dept_id   INT PRIMARY KEY,
  uni_id    INT REFERENCES university(uni_id),
  dept_name VARCHAR(100)
);

CREATE TABLE scientist (
  sci_id     INT PRIMARY KEY,
  firstname  VARCHAR(100),
  lastname   VARCHAR(100),
  uni_id     INT REFERENCES university(uni_id),
  dept_id    INT REFERENCES department(dept_id),
  birth_date DATE,
  gender     TEXT
);

CREATE TABLE research (
  research_id INT PRIMARY KEY,
  title       VARCHAR(255),
  begin_date  DATE DEFAULT current_date,
  end_date    DATE DEFAULT 'Unkown',
  sci_id      INT REFERENCES scientist(sci_id),
  status      VARCHAR(20)
);

CREATE TABLE publication (
  pub_id   INT PRIMARY KEY,
  title    VARCHAR(300),
  pub_year INT,
  venue    VARCHAR(100)
);

CREATE TABLE grant_funding (
  grant_id   INT PRIMARY KEY,
  sponsor    VARCHAR(120),
  amount     NUMERIC(12,2),
  start_date DATE,
  end_date   DATE
);

-- Junction tables (duplicates allowed for anomaly checking)
CREATE TABLE research_publication (
  research_id INT REFERENCES research(research_id),
  pub_id      INT REFERENCES publication(pub_id),
  PRIMARY KEY (research_id, pub_id)
);

CREATE TABLE research_grant (
  research_id INT REFERENCES research(research_id),
  grant_id    INT REFERENCES grant_funding(grant_id),
  PRIMARY KEY (research_id, grant_id)
);

